/* =========================================================
   GET TRANSLATION
========================================================= */

function getTranslation(language, key) {

    const parts =
        key.split(".");

    let value =
        translations[language];


    for (const part of parts) {

        if (!value) {
            return null;
        }

        value =
            value[part];
    }


    return value;
}


/* =========================================================
   CHANGE LANGUAGE
========================================================= */

function changeLanguage(language) {

    if (!translations[language]) {
        language = "en";
    }


    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.dataset.i18n;


            const translation =
                getTranslation(
                    language,
                    key
                );


            if (translation !== null) {

                element.textContent =
                    translation;
            }

        });


    /* HTML LANGUAGE */

    document.documentElement.lang =
        language;


    /* ACTIVE LANGUAGE BUTTON */

    document
        .querySelectorAll(".lang-btn")
        .forEach(button => {

            button.classList.toggle(
                "active",
                button.dataset.lang === language
            );

        });


    /* SAVE LANGUAGE */

    localStorage.setItem(
        "knowme-language",
        language
    );

    activeSiteLanguage = language;

    // Automatic defaults: HY → AMD, EN → USD, RU → RUB.
    // A manually selected currency remains unchanged across language switches.
    if (!priceCurrencyWasManuallySelected) {
        setPriceCurrency(defaultPriceCurrency(language), false);
    } else {
        setPriceCurrency(activePriceCurrency, false);
    }
}


